function haversineKm(lat2: number, lng2: number): number {
  const toRad = (d: number) => d * Math.PI / 180;
  const dLat = toRad(lat2 - ICN_LAT);
  const dLng = toRad(lng2 - ICN_LNG);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(ICN_LAT)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(a));
}

/**
 * 인천(ICN) 기준 추정 비행시간(분).
 * 대권거리 / 850km/h + 35분 지상 운영 시간.
 * 좌표 데이터 없으면 null.
 */
export function estimateFromICN(code: string): number | null {
  const c = AIRPORT_COORDS[code.toUpperCase()];
  if (!c) return null;
  const km = haversineKm(c[0], c[1]);
  return Math.max(60, Math.round(km / 850 * 60) + 35);
}

/**
 * 주어진 공항 코드 목록 중 정적 테이블에 없는 것을 추정해 반환.
 * Record<IATA, 분>
 */
export function estimateMissing(
  codes: string[],
  staticTable: Record<string, number>
): Record<string, number> {
  const result: Record<string, number> = {};
  for (const code of codes) {
    if (!code || code in staticTable) continue;
    const est = estimateFromICN(code);
    if (est !== null) result[code] = est;
  }
  return result;
}
